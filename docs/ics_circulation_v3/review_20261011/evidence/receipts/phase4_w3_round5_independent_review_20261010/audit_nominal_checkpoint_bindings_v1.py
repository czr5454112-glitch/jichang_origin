"""Read-only audit of SHA-bound locally generated checkpoint/request artifacts."""
from collections import Counter
from dataclasses import asdict
import json
from pathlib import Path
import pickle
import sys
from time import perf_counter, process_time

from audit_round5_full_cycle import Audit, ROOT, digest, file_hash, read
sys.path.insert(0, str(ROOT))
from scripts.experiments.ics_circulation_v3.role_coverage import CursorSimulation
from scripts.experiments.ics_circulation_v3.routing_cache_contract import routing_cache_state
from scripts.experiments.ics_circulation_v3.runtime import actual_action_key


def normalized(value):
    return json.loads(json.dumps(value, allow_nan=False))


def main():
    folder=ROOT/'outputs/experiments/ics_circulation_v3/phase4_w3_network_nominal_opportunities_repaired_20261010'
    output=ROOT/'outputs/experiments/ics_circulation_v3/phase4_w3_round5_independent_review_20261010/nominal_checkpoint_binding_audit.json'
    wall,cpu=perf_counter(),process_time()
    audit=Audit()
    protocol=read(folder/'protocol.json')
    for name,expected in read(folder/'full_input_manifest_start.json').items():
        audit.bind(folder/name,expected)
    for name,expected in protocol['source_sha256'].items():
        audit.bind(ROOT/'scripts/experiments/ics_circulation_v3'/name,expected)
    summary=read(folder/'collection_summary.json')
    if audit.errors:
        raise ValueError('Refusing pickle inspection because frozen trusted input bytes changed')
    counts=Counter()
    keys=set()
    for case in summary['cases']:
        audit.bind(folder/case['file'],case['sha256'])
        body=read(folder/case['file'])
        expected=[]
        for meta in body['attempts']:
            row=read(folder/'collections'/case['scene']/f"d{meta['decision_index']:04d}.json")
            identity=row['identity']
            counts['all_attempts']+=1
            counts['candidate_requests']+=row['candidate_count']
            counts[f"pool_size_{row['candidate_count']}"]+=1
            if not row['candidate_count']:
                audit.check('checkpoint_file' not in row,identity,'zero-candidate attempt should not create a forced branch checkpoint')
                continue
            path=folder/row['checkpoint_file']
            # The pickle is self-generated by this run, byte bound before loading.
            if audit.bind(path,row['checkpoint_sha256'])!=row['checkpoint_sha256']:
                raise ValueError('Refusing changed self-generated checkpoint')
            with path.open('rb') as stream:
                data=pickle.load(stream)
            cp,pool,future=data['checkpoint'],data['pool'],data['future']
            counts['owned_checkpoints']+=1
            audit.check(normalized(asdict(cp.state))==row['state'],identity,'checkpoint state differs from decision JSON')
            audit.check(normalized(asdict(cp.cursor))==row['cursor'],identity,'checkpoint cursor differs from decision JSON')
            audit.check(normalized([asdict(p) for p in pool])==row['candidates'],identity,'checkpoint candidate pool differs')
            audit.check(normalized([asdict(b) for b in future])==row['future_event_engine_only'],identity,'checkpoint future differs')
            pending=sorted((asdict(b) for bags in cp.base.pending_arrivals.values() for b in bags),key=lambda b:(b['arrival'],b['bag_id']))
            audit.check(normalized(pending)==row['future_event_engine_only'],identity,'remaining engine-only tape differs from supplied nominal future')
            audit.check(digest([asdict(b) for b in future])==row['future_sha256'],identity,'full nominal tape hash differs')
            restored=CursorSimulation.from_checkpoint(cp)
            audit.check(normalized(routing_cache_state(restored))==row['routing_cache'],identity,'checkpoint private routing cache differs')
            audit.check(restored.slow_controller.next_trigger_at==row['next_slow_trigger_at'],identity,'checkpoint slow clock differs')
            actual=[actual_action_key(cp.state,p,route_mode='next_edge') for p in pool]
            audit.check(actual==row['actual_action_keys'],identity,'semantic action key differs from owned candidate')
            audit.check(cp.cursor.pending_tray_id==row['tray_id'] and normalized([asdict(p) for p in cp.cursor.pending_options])==row['candidates'],identity,'routing program counter not at this candidate pool')
            for ordinal,key in enumerate(actual):
                request={'request_key':f"{case['scene']}_d{row['decision_index']:04d}_c{ordinal}",
                    'scene':case['scene'],'decision_index':row['decision_index'],'sample':identity,
                    'candidate':ordinal,'actual_action_key':key,'future_sha256':row['future_sha256'],
                    'checkpoint_file':row['checkpoint_file'],'checkpoint_sha256':row['checkpoint_sha256']}
                expected.append(request)
                audit.check(request['request_key'] not in keys,identity,'duplicate request identity')
                keys.add(request['request_key'])
        audit.check(expected==body['requests'],case['scene'],'request grid does not exactly bind all actual candidate ordinals')
        audit.check(len(expected)==case['requests'],case['scene'],'collection summary request count differs')
    audit.check((counts['all_attempts'],counts['owned_checkpoints'],counts['candidate_requests'])==(180,174,693),'denominator','not all actual attempts/nonempty candidates represented')
    changed=[p for p,h in audit.files.items() if file_hash(p)!=h]
    audit.check(not changed,folder,'bound files changed during read-only checkpoint audit')
    result={'schema':'ics_v3_nominal_owned_checkpoint_binding_audit_v1','run':str(folder),
        'checks':audit.count,'failed_checks':len(audit.errors),'errors':audit.errors,'counts':dict(counts),
        'bound_files':len(audit.files),'all_bound_files_unchanged':not changed,
        'script_sha256':file_hash(__file__),'helper_sha256':file_hash(Path(__file__).with_name('audit_round5_full_cycle.py')),
        'wall_seconds':perf_counter()-wall,'cpu_seconds':process_time()-cpu,
        'scope':'Only SHA-validated locally generated pickle deserialization and cloned engine restoration for cache inspection; no simulation ticks, route generation, decisions or new counterfactual rollouts.'}
    with output.open('x',encoding='utf-8') as stream:
        json.dump(result,stream,ensure_ascii=False,indent=2)
    print(json.dumps({k:result[k] for k in ('checks','failed_checks','counts','bound_files','wall_seconds')}))
    return bool(audit.errors)

if __name__=='__main__':
    raise SystemExit(main())
